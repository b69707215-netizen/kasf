/* Розбір поста: ГДЕ дрон зараз і КУДИ летить (можлива ціль) */
function extractTracks(txt) {
  const low = " " + txt.toLowerCase().replace(/ʼ/g, "'") + " ";
  const out = [];
  for (const p of PLACES) {
    for (const v of p.v) {
      const idx = low.indexOf(v);
      if (idx === -1) continue;
      // що написано перед назвою місця: курс/напрямок → ціль, "над/в районі" → позиція зараз
      const before = low.slice(Math.max(0, idx - 45), idx);
      const isTarget = /(курсом на|курс на|курсе на|в бік|у бік|довернув на|повернувся на|довернул на|повернулся на|в напрямку|напрямок|(?:^|\s)до\s*$)/i.test(before);
      const isPos = /(над|в районі|у районі|в район|районе|пролітає|пролетает|пролетел|працює|зараз)/i.test(before);
      out.push({ name: p.name, ll: p.ll, role: isTarget ? "target" : "pos" });
      break;
    }
    if (out.length >= 5) break;   // максимум 5 точок з одного поста
  }
  return out;
}

