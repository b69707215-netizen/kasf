function extractDirection(txt) {
  const m = txt.match(/(?:в напрямку|напрямок|направление|курсом на|курс на|в бік|у бік|довернув на|повернувся на|довернул на|повернулся на)\s+([^.;!?]{2,45})/i);
  return m ? m[1].trim() : null;
}

